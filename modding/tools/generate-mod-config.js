const fs = require('fs');
const path = require('path');

const MODS_DIR = path.resolve(__dirname, '../../gui-js/libs/mods');
const OUTPUT_FILE_FRONTEND = path.resolve(__dirname, '../../gui-js/libs/shared/src/lib/modding/mod-config.frontend.generated.ts');
const OUTPUT_FILE_BACKEND = path.resolve(__dirname, '../../gui-js/libs/shared/src/lib/modding/mod-config.backend.generated.ts');

console.log(`Scanning for mods in: ${MODS_DIR}`);

// Native recursive find for manifest.json
function findManifests(dir, fileList = []) {
    if (!fs.existsSync(dir)) return fileList;
    const files = fs.readdirSync(dir);
    files.forEach(file => {
        const filePath = path.join(dir, file);
        const stat = fs.statSync(filePath);
        if (stat.isDirectory()) {
            if (file !== 'node_modules' && file !== '.git') {
                findManifests(filePath, fileList);
            }
        } else {
            if (file === 'manifest.json') {
                fileList.push(filePath);
            }
        }
    });
    return fileList;
}

const modManifests = findManifests(MODS_DIR);
const activeMods = [];
const modRoutes = [];
const modIpcHandlers = [];
const contributions = [];

// Helper to escape strings for TS output
const json = (obj) => JSON.stringify(obj, null, 2);

console.log(`Found ${modManifests.length} potential manifest(s).`);

modManifests.forEach(manifestPath => {
    try {
        const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

        if (!manifest.id) {
            console.warn(`Skipping invalid manifest at ${manifestPath}: missing 'id'`);
            return;
        }

        console.log(`Processing mod: ${manifest.id}`);
        activeMods.push(manifest.id);

        if (manifest.contributions) {
            // Process Routes
            if (manifest.contributions.routes) {
                manifest.contributions.routes.forEach(route => {
                    modRoutes.push({
                        path: route.path,
                        modId: manifest.id,
                        moduleName: route.moduleName
                    });
                });
            }

            // Process Menus
            if (manifest.contributions.menus) {
                manifest.contributions.menus.forEach(menu => {
                    menu.modId = manifest.id;
                    contributions.push(menu);
                });
            }

            // Process IPC
            if (manifest.contributions.ipc) {
                manifest.contributions.ipc.forEach(ipc => {
                    modIpcHandlers.push({
                        channel: ipc.channel,
                        moduleName: 'ipcHandlers',
                        // CRITICAL: Point directly to the IPC file to avoid importing Angular components from index.ts
                        // Path from gui-js/libs/shared/src/lib/modding/mod-config.backend.generated.ts
                        // To gui-js/libs/mods/<modId>/src/lib/ipc-handlers.ts
                        importPath: `../../../../mods/${manifest.id}/src/lib/ipc-handlers`
                    });
                });
            }
        }

    } catch (e) {
        console.error(`Error processing ${manifestPath}:`, e);
    }
});

const frontendContent = `
// AUTO-GENERATED BY tools/generate-mod-config.js
// DO NOT EDIT MANUALLY

import { Routes } from '@angular/router';

export const activeMods = ${json(activeMods)};

export const modMenuContributions = ${json(contributions)};

export const modRoutes: Routes = [
${modRoutes.map(r => `  { path: '${r.path}', loadChildren: () => import('@minsky/${r.modId}').then(m => m.${r.moduleName || 'ScenarioLoaderModule'}) },`).join('\n')}
];
`;

const backendContent = `
// AUTO-GENERATED BY tools/generate-mod-config.js
// DO NOT EDIT MANUALLY

export const modIpcHandlers = [
${modIpcHandlers.map(h => `  { channel: '${h.channel}', handler: async (event, ...args: any[]) => ((await import('${h.importPath}')).${h.moduleName}['${h.channel}'] as any)(...args) },`).join('\n')}
];
`;

fs.writeFileSync(OUTPUT_FILE_FRONTEND, frontendContent);
fs.writeFileSync(OUTPUT_FILE_BACKEND, backendContent);

console.log(`Generated frontend config at: ${OUTPUT_FILE_FRONTEND}`);
console.log(`Generated backend config at: ${OUTPUT_FILE_BACKEND}`);
